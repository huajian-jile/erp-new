package com.example.wmsnew.gen;

import com.github.javaparser.StaticJavaParser;
import com.github.javaparser.ast.CompilationUnit;
import com.github.javaparser.ast.body.ClassOrInterfaceDeclaration;
import com.github.javaparser.ast.expr.AnnotationExpr;
import com.github.javaparser.ast.expr.MemberValuePair;
import com.github.javaparser.ast.expr.NormalAnnotationExpr;
import com.github.javaparser.ast.expr.SingleMemberAnnotationExpr;
import com.github.javaparser.ast.expr.StringLiteralExpr;
import com.github.javaparser.ast.visitor.VoidVisitorAdapter;

import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.nio.file.attribute.BasicFileAttributes;
import java.util.*;
import java.util.stream.Collectors;

/**
 * 扫描 @AutoCrud 实体，生成 Repository、Service、Controller、建表 SQL，输出到 src 目录。
 * 由 Maven 在 process-classes 阶段调用。
 */
public class AutoCrudGenerator {

    private static final String SRC = "src/main/java";
    private static final String BASE = "com/example/wmsnew";
    private static final String REPO_DIR = "src/main/java/" + BASE + "/repository";
    private static final String SERVICE_DIR = "src/main/java/" + BASE + "/service";
    private static final String CONTROLLER_DIR = "src/main/java/" + BASE + "/controller";
    private static final String SQL_FILE = "src/main/resources/sql/99_auto_crud.sql";
    private static final String CRUD_JSON = "src/main/resources/static/crud-entities.json";

    public static void main(String[] args) throws Exception {
        Path baseDir = Paths.get(System.getProperty("user.dir", "."));
        Path srcDir = baseDir.resolve(SRC);
        if (!Files.exists(srcDir)) {
            System.err.println("[AutoCrud] Not found: " + srcDir);
            return;
        }

        List<EntityMeta> entities = new ArrayList<>();
        Files.walkFileTree(srcDir, new SimpleFileVisitor<>() {
            @Override
            public FileVisitResult visitFile(Path file, BasicFileAttributes attrs) {
                if (file.toString().endsWith(".java")) {
                    parseFile(file).ifPresent(entities::add);
                }
                return FileVisitResult.CONTINUE;
            }
        });

        Files.createDirectories(baseDir.resolve(REPO_DIR));
        Files.createDirectories(baseDir.resolve(SERVICE_DIR));
        Files.createDirectories(baseDir.resolve(CONTROLLER_DIR));
        Files.createDirectories(baseDir.resolve(SQL_FILE).getParent());

        StringBuilder sql = new StringBuilder();
        sql.append("-- Auto-generated by AutoCrudGenerator. DO NOT EDIT.\n\n");

        if (entities.isEmpty()) {
            System.out.println("[AutoCrud] 未发现 @AutoCrud 实体，生成占位 SQL");
            sql.append("SELECT 1;\n");
            Files.writeString(baseDir.resolve(SQL_FILE), sql.toString(), StandardCharsets.UTF_8);
            Files.createDirectories(baseDir.resolve(CRUD_JSON).getParent());
            Files.writeString(baseDir.resolve(CRUD_JSON), "[]\n", StandardCharsets.UTF_8);
            return;
        }

        String basePkg = "com.example.wmsnew";
        for (EntityMeta e : entities) {
            generateRepo(baseDir, e, basePkg);
            generateService(baseDir, e, basePkg);
            generateController(baseDir, e, basePkg);
            sql.append(toCreateTable(e)).append("\n");
        }

        Files.writeString(baseDir.resolve(SQL_FILE), sql.toString(), StandardCharsets.UTF_8);
        Files.createDirectories(baseDir.resolve(CRUD_JSON).getParent());
        Files.writeString(baseDir.resolve(CRUD_JSON), toCrudEntitiesJson(entities), StandardCharsets.UTF_8);
        System.out.println("[AutoCrud] 已生成 " + entities.size() + " 个 Repository/Service/Controller + " + SQL_FILE);
    }

    private static Optional<EntityMeta> parseFile(Path file) {
        try {
            String src = Files.readString(file, StandardCharsets.UTF_8);
            CompilationUnit cu = StaticJavaParser.parse(src);
            EntityCollector collector = new EntityCollector();
            cu.accept(collector, null);
            return Optional.ofNullable(collector.entity);
        } catch (Exception e) {
            return Optional.empty();
        }
    }

    private static class EntityCollector extends VoidVisitorAdapter<Void> {
        EntityMeta entity;

        @Override
        public void visit(ClassOrInterfaceDeclaration n, Void arg) {
            if (n.isInterface()) return;
            boolean hasAutoCrud = n.getAnnotations().stream()
                    .anyMatch(a -> "AutoCrud".equals(a.getNameAsString()));
            if (!hasAutoCrud) return;

            String tableName = n.getAnnotations().stream()
                    .filter(a -> "Table".equals(a.getNameAsString()))
                    .findFirst()
                    .flatMap(AutoCrudGenerator::extractTableName)
                    .orElse("wms_" + toSnakeCase(n.getNameAsString()));

            if (!tableName.startsWith("wms_")) {
                tableName = "wms_" + tableName.replace("-", "_");
            }

            String pkg = n.findCompilationUnit()
                    .flatMap(cu -> cu.getPackageDeclaration().map(pd -> pd.getNameAsString()))
                    .orElse("");
            String simpleName = n.getNameAsString();
            List<FieldMeta> fields = n.getFields().stream()
                    .filter(f -> !f.isStatic())
                    .flatMap(f -> f.getVariables().stream()
                            .map(v -> new FieldMeta(
                                    v.getNameAsString(),
                                    v.getTypeAsString(),
                                    "id".equalsIgnoreCase(v.getNameAsString()))))
                    .collect(Collectors.toList());

            entity = new EntityMeta(simpleName, pkg, tableName, fields);
        }
    }

    private static Optional<String> extractTableName(AnnotationExpr a) {
        if (a instanceof SingleMemberAnnotationExpr sm) {
            if (sm.getMemberValue() instanceof StringLiteralExpr sl) {
                return Optional.of(sl.getValue());
            }
        }
        if (a instanceof NormalAnnotationExpr n) {
            return n.getPairs().stream()
                    .filter(p -> "value".equals(p.getNameAsString()))
                    .findFirst()
                    .map(MemberValuePair::getValue)
                    .filter(v -> v instanceof StringLiteralExpr)
                    .map(v -> ((StringLiteralExpr) v).getValue());
        }
        return Optional.empty();
    }

    private static String toSnakeCase(String camel) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < camel.length(); i++) {
            char c = camel.charAt(i);
            if (Character.isUpperCase(c)) {
                if (i > 0) sb.append('_');
                sb.append(Character.toLowerCase(c));
            } else {
                sb.append(c);
            }
        }
        return sb.toString();
    }

    private static void generateRepo(Path baseDir, EntityMeta e, String basePkg) throws java.io.IOException {
        Path file = baseDir.resolve(REPO_DIR).resolve(e.simpleName + "Repository.java");
        String entityClass = e.pkg + "." + e.simpleName;

        String code = "package " + basePkg + ".repository;\n\n" +
                "import org.springframework.data.repository.CrudRepository;\n" +
                "import " + entityClass + ";\n\n" +
                "/** Auto-generated. DO NOT EDIT. */\n" +
                "public interface " + e.simpleName + "Repository extends CrudRepository<" + e.simpleName + ", Long> {\n" +
                "}\n";

        Files.writeString(file, code, StandardCharsets.UTF_8);
    }

    private static void generateService(Path baseDir, EntityMeta e, String basePkg) throws java.io.IOException {
        Path file = baseDir.resolve(SERVICE_DIR).resolve(e.simpleName + "Service.java");
        String entityClass = e.pkg + "." + e.simpleName;

        String code = "package " + basePkg + ".service;\n\n" +
                "import " + entityClass + ";\n" +
                "import " + basePkg + ".repository." + e.simpleName + "Repository;\n" +
                "import org.springframework.stereotype.Service;\n\n" +
                "import java.util.Optional;\n\n" +
                "/** Auto-generated. DO NOT EDIT. */\n" +
                "@Service\n" +
                "public class " + e.simpleName + "Service {\n" +
                "    private final " + e.simpleName + "Repository repo;\n\n" +
                "    public " + e.simpleName + "Service(" + e.simpleName + "Repository repo) {\n" +
                "        this.repo = repo;\n" +
                "    }\n\n" +
                "    public " + e.simpleName + " save(" + e.simpleName + " e) { return repo.save(e); }\n" +
                "    public Optional<" + e.simpleName + "> findById(Long id) { return repo.findById(id); }\n" +
                "    public Iterable<" + e.simpleName + "> findAll() { return repo.findAll(); }\n" +
                "    public void deleteById(Long id) { repo.deleteById(id); }\n" +
                "}\n";

        Files.writeString(file, code, StandardCharsets.UTF_8);
    }

    private static void generateController(Path baseDir, EntityMeta e, String basePkg) throws java.io.IOException {
        Path file = baseDir.resolve(CONTROLLER_DIR).resolve(e.simpleName + "Controller.java");
        String entityClass = e.pkg + "." + e.simpleName;
        String apiPath = toKebabCase(e.simpleName);

        String code = "package " + basePkg + ".controller;\n\n" +
                "import " + entityClass + ";\n" +
                "import " + basePkg + ".service." + e.simpleName + "Service;\n" +
                "import org.springframework.http.HttpStatus;\n" +
                "import org.springframework.web.bind.annotation.*;\n\n" +
                "import java.util.Optional;\n\n" +
                "/** Auto-generated CRUD API. DO NOT EDIT. */\n" +
                "@RestController\n" +
                "@RequestMapping(\"/api/crud/" + apiPath + "\")\n" +
                "public class " + e.simpleName + "Controller {\n" +
                "    private final " + e.simpleName + "Service service;\n\n" +
                "    public " + e.simpleName + "Controller(" + e.simpleName + "Service service) {\n" +
                "        this.service = service;\n" +
                "    }\n\n" +
                "    @GetMapping\n" +
                "    public Iterable<" + e.simpleName + "> list() { return service.findAll(); }\n\n" +
                "    @GetMapping(\"/{id}\")\n" +
                "    public Optional<" + e.simpleName + "> get(@PathVariable Long id) { return service.findById(id); }\n\n" +
                "    @PostMapping\n" +
                "    @ResponseStatus(HttpStatus.CREATED)\n" +
                "    public " + e.simpleName + " create(@RequestBody " + e.simpleName + " e) { return service.save(e); }\n\n" +
                "    @PutMapping(\"/{id}\")\n" +
                "    public " + e.simpleName + " update(@PathVariable Long id, @RequestBody " + e.simpleName + " e) {\n" +
                "        e.setId(id);\n" +
                "        return service.save(e);\n" +
                "    }\n\n" +
                "    @DeleteMapping(\"/{id}\")\n" +
                "    @ResponseStatus(HttpStatus.NO_CONTENT)\n" +
                "    public void delete(@PathVariable Long id) { service.deleteById(id); }\n" +
                "}\n";

        Files.writeString(file, code, StandardCharsets.UTF_8);
    }

    private static String toCrudEntitiesJson(List<EntityMeta> entities) {
        StringBuilder sb = new StringBuilder();
        sb.append("[\n");
        for (int i = 0; i < entities.size(); i++) {
            EntityMeta e = entities.get(i);
            sb.append("  {\n");
            sb.append("    \"apiPath\": \"").append(toKebabCase(e.simpleName)).append("\",\n");
            sb.append("    \"displayName\": \"").append(toDisplayName(e.simpleName)).append("\",\n");
            sb.append("    \"fields\": [\n");
            for (int j = 0; j < e.fields.size(); j++) {
                FieldMeta f = e.fields.get(j);
                String type = toFrontendType(f.javaType);
                String label = toFieldLabel(f.name);
                sb.append("      {\"name\": \"").append(f.name).append("\", \"label\": \"").append(escapeJson(label)).append("\", \"type\": \"").append(type).append("\", \"editable\": ").append(!f.isId).append("}");
                if (j < e.fields.size() - 1) sb.append(",");
                sb.append("\n");
            }
            sb.append("    ]\n");
            sb.append("  }");
            if (i < entities.size() - 1) sb.append(",");
            sb.append("\n");
        }
        sb.append("]\n");
        return sb.toString();
    }

    private static String toDisplayName(String simpleName) {
        String base = simpleName.replaceAll("Entity$", "");
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < base.length(); i++) {
            char c = base.charAt(i);
            if (Character.isUpperCase(c) && i > 0) sb.append(" ");
            sb.append(i == 0 ? c : Character.toLowerCase(c));
        }
        return sb.toString() + "实体";
    }

    private static String toFieldLabel(String name) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < name.length(); i++) {
            char c = name.charAt(i);
            if (Character.isUpperCase(c) && i > 0) sb.append(" ");
            sb.append(i == 0 ? Character.toUpperCase(c) : Character.toLowerCase(c));
        }
        return sb.toString().replace("Created at", "创建时间").replace("Updated at", "更新时间");
    }

    private static String toFrontendType(String javaType) {
        return switch (javaType) {
            case "long", "Long", "int", "Integer" -> "number";
            case "LocalDateTime", "java.time.LocalDateTime" -> "datetime";
            case "boolean", "Boolean" -> "boolean";
            case "double", "Double", "float", "Float", "BigDecimal", "java.math.BigDecimal" -> "number";
            default -> "string";
        };
    }

    private static String escapeJson(String s) {
        return s.replace("\\", "\\\\").replace("\"", "\\\"");
    }

    private static String toKebabCase(String camel) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < camel.length(); i++) {
            char c = camel.charAt(i);
            if (Character.isUpperCase(c)) {
                if (i > 0) sb.append('-');
                sb.append(Character.toLowerCase(c));
            } else {
                sb.append(c);
            }
        }
        return sb.toString();
    }

    private static String toCreateTable(EntityMeta e) {
        StringBuilder sb = new StringBuilder();
        sb.append("CREATE TABLE IF NOT EXISTS ").append(e.tableName).append(" (\n");
        List<String> cols = new ArrayList<>();
        for (FieldMeta f : e.fields) {
            String sqlType = toSqlType(f.javaType, f.isId);
            String col = "  " + toSnakeCase(f.name) + " " + sqlType;
            if (f.isId) col += " PRIMARY KEY AUTO_INCREMENT";
            cols.add(col);
        }
        sb.append(String.join(",\n", cols)).append("\n);\n");
        return sb.toString();
    }

    private static String toSqlType(String javaType, boolean isId) {
        if (isId) return "BIGINT";
        return switch (javaType) {
            case "long", "Long" -> "BIGINT NULL";
            case "int", "Integer" -> "INT NULL";
            case "String" -> "VARCHAR(255) NULL";
            case "LocalDateTime", "java.time.LocalDateTime" -> "DATETIME NULL";
            case "boolean", "Boolean" -> "TINYINT(1) NULL";
            case "double", "Double" -> "DOUBLE NULL";
            case "float", "Float" -> "FLOAT NULL";
            case "BigDecimal", "java.math.BigDecimal" -> "DECIMAL(19,4) NULL";
            default -> "VARCHAR(255) NULL";
        };
    }

    private static class EntityMeta {
        final String simpleName;
        final String pkg;
        final String tableName;
        final List<FieldMeta> fields;

        EntityMeta(String simpleName, String pkg, String tableName, List<FieldMeta> fields) {
            this.simpleName = simpleName;
            this.pkg = pkg;
            this.tableName = tableName;
            this.fields = fields;
        }
    }

    private static class FieldMeta {
        final String name;
        final String javaType;
        final boolean isId;

        FieldMeta(String name, String javaType, boolean isId) {
            this.name = name;
            this.javaType = javaType;
            this.isId = isId;
        }
    }
}
