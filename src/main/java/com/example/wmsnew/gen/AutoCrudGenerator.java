    private static String toCrudEntitiesJson(List<EntityMeta> entities) {
        StringBuilder sb = new StringBuilder();
        sb.append("[\n");
        for (int i = 0; i < entities.size(); i++) {
            EntityMeta e = entities.get(i);
            sb.append("  {\n");
            sb.append("    \"apiPath\": \"").append(toKebabCase(e.simpleName)).append("\",\n");
            sb.append("    \"displayName\": \"").append(toDisplayName(e.simpleName)).append("\",\n");
            sb.append("    \"fields\": [\n");
            for (int j = 0; j < e.fields.size(); j++) {
                FieldMeta f = e.fields.get(j);
                String type = toFrontendType(f.javaType);
                String label = toFieldLabel(f.name);
                sb.append("      {\"name\": \"").append(f.name).append("\", \"label\": \"").append(escapeJson(label)).append("\", \"type\": \"").append(type).append("\", \"editable\": ").append(!f.isId).append("}");
                if (j < e.fields.size() - 1) sb.append(",");
                sb.append("\n");
            }
            sb.append("    ]");
            if (!e.children.isEmpty()) {
                ChildMeta c = e.children.get(0);
                sb.append(",\n    \"children\": [{\n");
                sb.append("      \"collectionField\": \"").append(c.collectionField).append("\",\n");
                sb.append("      \"displayName\": \"").append(toDisplayName(c.simpleName)).append("\",\n");
                sb.append("      \"fields\": [\n");
                for (int j = 0; j < c.fields.size(); j++) {
                    FieldMeta f = c.fields.get(j);
                    String type = toFrontendType(f.javaType);
                    String label = toFieldLabel(f.name);
                    boolean editable = !f.isId && !f.name.equalsIgnoreCase(toCamelCase(c.fkColumn));
                    sb.append("        {\"name\": \"").append(f.name).append("\", \"label\": \"").append(escapeJson(label)).append("\", \"type\": \"").append(type).append("\", \"editable\": ").append(editable).append("}");
                    if (j < c.fields.size() - 1) sb.append(",");
                    sb.append("\n");
                }
                sb.append("      ]\n    }]");
            }
            sb.append("\n  }");
            if (i < entities.size() - 1) sb.append(",");
            sb.append("\n");
        }
        sb.append("]\n");
        return sb.toString();
    }

    private static String toDisplayName(String simpleName) {
        String base = simpleName.replaceAll("Entity$", "");
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < base.length(); i++) {
            char c = base.charAt(i);
            if (Character.isUpperCase(c) && i > 0) sb.append(" ");
            sb.append(i == 0 ? c : Character.toLowerCase(c));
        }
        return sb.toString() + "实体";
    }

    private static String toFieldLabel(String name) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < name.length(); i++) {
            char c = name.charAt(i);
            if (Character.isUpperCase(c) && i > 0) sb.append(" ");
            sb.append(i == 0 ? Character.toUpperCase(c) : Character.toLowerCase(c));
        }
        return sb.toString().replace("Created at", "创建时间").replace("Updated at", "更新时间");
    }

    private static String toFrontendType(String javaType) {
        return switch (javaType) {
            case "long", "Long", "int", "Integer" -> "number";
            case "LocalDateTime", "java.time.LocalDateTime" -> "datetime";
            case "boolean", "Boolean" -> "boolean";
            case "double", "Double", "float", "Float", "BigDecimal", "java.math.BigDecimal" -> "number";
            default -> "string";
        };
    }

    private static String escapeJson(String s) {
        return s.replace("\\", "\\\\").replace("\"", "\\\"");
    }

    private static String toKebabCase(String camel) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < camel.length(); i++) {
            char c = camel.charAt(i);
            if (Character.isUpperCase(c)) {
                if (i > 0) sb.append('-');
                sb.append(Character.toLowerCase(c));
            } else {
                sb.append(c);
            }
        }
        return sb.toString();
    }

    private static String toCreateTable(EntityMeta e) {
        StringBuilder sb = new StringBuilder();
        sb.append("CREATE TABLE IF NOT EXISTS ").append(e.tableName).append(" (\n");
        List<String> cols = new ArrayList<>();
        for (FieldMeta f : e.fields) {
            String sqlType = toSqlType(f.javaType, f.isId);
            String col = "  " + toSnakeCase(f.name) + " " + sqlType;
            if (f.isId) col += " PRIMARY KEY AUTO_INCREMENT";
            cols.add(col);
        }
        sb.append(String.join(",\n", cols)).append("\n);\n");

        for (ChildMeta c : e.children) {
            sb.append("\nCREATE TABLE IF NOT EXISTS ").append(c.tableName).append(" (\n");
            List<String> ccols = new ArrayList<>();
            for (FieldMeta f : c.fields) {
                String sqlType = toSqlType(f.javaType, f.isId);
                String col = "  " + toSnakeCase(f.name) + " " + sqlType;
                if (f.isId) col += " PRIMARY KEY AUTO_INCREMENT";
                ccols.add(col);
            }
            sb.append(String.join(",\n", ccols)).append(",\n");
            sb.append("  KEY idx_").append(c.tableName.replace("wms_", "fk_")).append("_").append(c.fkColumn).append(" (").append(c.fkColumn).append(")\n");
            sb.append(");\n");
        }
        return sb.toString();
    }

    private static String toSqlType(String javaType, boolean isId) {
        if (isId) return "BIGINT";
        return switch (javaType) {
            case "long", "Long" -> "BIGINT NULL";
            case "int", "Integer" -> "INT NULL";
            case "String" -> "VARCHAR(255) NULL";
            case "LocalDateTime", "java.time.LocalDateTime" -> "DATETIME NULL";
            case "boolean", "Boolean" -> "TINYINT(1) NULL";
            case "double", "Double" -> "DOUBLE NULL";
            case "float", "Float" -> "FLOAT NULL";
            case "BigDecimal", "java.math.BigDecimal" -> "DECIMAL(19,4) NULL";
            default -> "VARCHAR(255) NULL";
        };
    }

    private static class EntityMeta {
        final String simpleName;
        final String pkg;
        final String tableName;
        final List<FieldMeta> fields;
        final List<ChildMeta> children;

        EntityMeta(String simpleName, String pkg, String tableName, List<FieldMeta> fields, List<ChildMeta> children) {
            this.simpleName = simpleName;
            this.pkg = pkg;
            this.tableName = tableName;
            this.fields = fields;
            this.children = children != null ? children : List.of();
        }
    }

    private static class ChildMeta {
        final String simpleName;
        final String tableName;
        final String fkColumn;
        final String collectionField;
        final List<FieldMeta> fields;

        ChildMeta(String simpleName, String tableName, String fkColumn, String collectionField, List<FieldMeta> fields) {
            this.simpleName = simpleName;
            this.tableName = tableName;
            this.fkColumn = fkColumn;
            this.collectionField = collectionField;
            this.fields = fields;
        }
    }

    private static class FieldMeta {
        final String name;
        final String javaType;
        final boolean isId;

        FieldMeta(String name, String javaType, boolean isId) {
            this.name = name;
            this.javaType = javaType;
            this.isId = isId;
        }
    }
